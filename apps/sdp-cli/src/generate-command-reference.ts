import { execFileSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { commands } from "./commands";
import { operationById } from "./contract";

const target = new URL("../COMMANDS.md", import.meta.url);
const rows = [...commands]
  .sort((a, b) => a.words.join(" ").localeCompare(b.words.join(" "), "en"))
  .map((command) => {
    const operation = operationById(command.operationId);
    const parameters = operation.parameters
      .filter((parameter) => parameter.location === "path")
      .map((parameter) =>
        parameter.name === "projectId" || parameter.name === "orgId"
          ? `[${parameter.name}]`
          : `<${parameter.name}>`
      );
    const invocation = ["sdp", ...command.words, ...parameters].join(" ");
    return `| \`${invocation}\` | ${operation.method} | \`${operation.path}\` |`;
  });
const markdown = [
  "<!-- Generated by pnpm generate:cli. Do not edit by hand. -->",
  "# SDP command reference",
  "",
  "Each command makes one API request. Run a command with `--help` for its authentication, flags, signing responsibilities, and response details. IDs follow all command words; optional project and organization IDs can also come from flags or environment variables.",
  "",
  "| Command | Method | Endpoint |",
  "| --- | --- | --- |",
  ...rows,
  "",
].join("\n");
const reference = execFileSync(
  fileURLToPath(new URL("../../../node_modules/.bin/biome", import.meta.url)),
  ["format", "--stdin-file-path", fileURLToPath(target)],
  { input: markdown, encoding: "utf8", maxBuffer: 16 * 1024 * 1024, timeout: 30_000 }
);
if (process.argv.includes("--check")) {
  if ((await readFile(target, "utf8")) !== reference)
    throw new Error("CLI command reference is stale. Run pnpm generate:cli.");
  console.log(`CLI command reference is current (${commands.length} commands).`);
} else {
  await writeFile(target, reference);
  console.log(`Generated CLI command reference (${commands.length} commands).`);
}
